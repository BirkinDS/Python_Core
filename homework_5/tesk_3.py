# Напишите функцию, которая принимает количество повторных запусков теста и значение таймаута.
# Количество повторных запусков должно находиться в диапазоне от 0 до 5, а таймаут должен быть положительным числом.
# Если переданные значения не соответствуют этим требованиям, самостоятельно создайте исключение ValueError
# с помощью raise и добавьте понятное описание причины ошибки.
# Вызов функции необходимо поместить в try/except и корректно обработать созданные исключения.
# Проверьте работу программы минимум на трёх наборах данных: корректные значения, отрицательный таймаут и слишком большое количество повторных запусков.

# solution

def set_test_params(retries, timeout):
    # Проверяем количество повторных запусков
    if retries < 0:
        raise ValueError(f"Количество повторных запусков не может быть отрицательным: {retries}")
    if retries > 5:
        raise ValueError(f"Количество повторных запусков не должно быть больше 5: {retries}")

    # Проверяем таймаут
    if timeout <= 0:
        raise ValueError(f"Таймаут должен быть положительным числом: {timeout}")

    # Если все проверки прошли — возвращаем настройки
    return {"retries": retries, "timeout": timeout}

# 1. Корректные значения
try:
    result = set_test_params(3, 10)
    print("Всё хорошо, параметры:", result)
except ValueError as e:
    print("Ошибка:", e)
# 2. Отрицательный таймаут
try:
    result = set_test_params(2, -5)
    print("Всё хорошо, параметры:", result)
except ValueError as e:
    print("Ошибка:", e)
# 3. Слишком много повторных запусков
try:
    result = set_test_params(10, 30)
    print("Всё хорошо, параметры:", result)
except ValueError as e:
    print("Ошибка:", e)