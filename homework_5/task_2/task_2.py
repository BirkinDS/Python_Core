# Создайте JSON-файл с тестовыми пользователями для проверки авторизации.
# Для каждого пользователя должны храниться логин, пароль и ожидаемый результат авторизации. Напишите программу,
# которая открывает JSON-файл, загружает данные и выводит информацию о каждом тестовом пользователе.
# Программа должна корректно обрабатывать ситуации, когда файл не существует, содержимое файла невозможно прочитать
# как JSON или у пользователя отсутствует обязательное поле.
# Для обработки ошибок используйте try/except, соответствующие типы исключений и получение информации об ошибке через as e.

# solution
import json
# Имя файла с тестовыми пользователями
filename = "users.json"

try:
    # Пытаемся открыть файл
    with open(filename, "r", encoding="utf-8") as f:
        data = json.load(f)
    # Проверяем, что в файле именно список
    if not isinstance(data, list):
        print("Ошибка: в файле должен быть список пользователей")
    else:
        # Идём по каждому пользователю
        for i, user in enumerate(data, start=1):
            try:
                # Пытаемся достать обязательные поля
                login = user["login"]
                password = user["password"]
                expected = user["expected"]

                print(f"Пользователь #{i}")
                print(f"  Логин: {login}")
                print(f"  Пароль: {password}")
                print(f"  Ожидаемый результат: {expected}")

            except KeyError as e:
                # Если какого-то поля нет
                print(f"Пользователь #{i}: отсутствует обязательное поле {e}")

except FileNotFoundError as e:
    print(f"Файл не найден: {e}")
except json.JSONDecodeError as e:
    print(f"Не удалось прочитать JSON: {e}")
except PermissionError as e:
    print(f"Нет доступа к файлу: {e}")
except Exception as e:
    # Любая другая ошибка
    print(f"Произошла непредвиденная ошибка: {e}")